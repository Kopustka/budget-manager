-- Создание кошельков и категорий из интерфейса: имена внутри пользователя
-- должны быть различимы, иначе в матрице появятся две одинаковые плитки и
-- пользователь не поймёт, в какую из них он списывает.
--
-- Регистр не считаем значимым: «Кафе» и «кафе» — одно и то же для человека.
CREATE UNIQUE INDEX IF NOT EXISTS uq_wallets_user_name
  ON wallets (user_id, lower(name));

-- Вид входит в ключ: «Подработка» может быть и источником дохода, и категорией
-- расхода — это разные сущности в разных половинах матрицы.
CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_user_kind_name
  ON categories (user_id, kind, lower(name));
